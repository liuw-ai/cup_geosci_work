from __future__ import annotations

import subprocess
import sys
from pathlib import Path

import pytest

from scripts.prepare_release_env import render_manifest
from scripts.build_phase3_manifest import image_digest, release_env_values


DIGEST_A = "sha256:" + "a" * 64
DIGEST_B = "sha256:" + "b" * 64
DIGEST_C = "sha256:" + "c" * 64
DIGEST_D = "sha256:" + "d" * 64


def _image(name: str, digest: str) -> str:
    return f"registry.example/{name}@{digest}"


def test_render_release_manifest_contains_one_immutable_runtime_identity() -> None:
    manifest = render_manifest(
        version="2026.10.10-1",
        git_sha="abcdef1234567890",
        built_at="2026-10-10T01:30:00Z",
        application_image=_image("job-hub", DIGEST_A),
        browser_image=_image("job-hub-browser", DIGEST_B),
        browser_deps_image=_image("job-hub-browser-deps", DIGEST_C),
        headless_shell_image=_image("headless-shell", DIGEST_D),
    )

    assert f"APP_RELEASE_IMAGE_SHA={DIGEST_A}" in manifest
    assert f"JOB_HUB_IMAGE=registry.example/job-hub@{DIGEST_A}" in manifest
    assert f"RUNTIME_IMAGE=registry.example/job-hub@{DIGEST_A}" in manifest
    assert ":latest" not in manifest


@pytest.mark.parametrize(
    ("application_image", "expected"),
    [
        ("registry.example/job-hub:release-2026-10-10", "application_image"),
        (_image("job-hub", "sha256:short"), "application_image"),
    ],
)
def test_render_release_manifest_rejects_mutable_or_invalid_images(
    application_image: str, expected: str
) -> None:
    with pytest.raises(ValueError, match=expected):
        render_manifest(
            version="2026.10.10-1",
            git_sha="abcdef1234567890",
            built_at="2026-10-10T01:30:00Z",
            application_image=application_image,
            browser_image=_image("job-hub-browser", DIGEST_B),
            browser_deps_image=_image("job-hub-browser-deps", DIGEST_C),
            headless_shell_image=_image("headless-shell", DIGEST_D),
        )


def test_release_manifest_cli_writes_only_requested_output(tmp_path) -> None:
    output = tmp_path / "release.env"
    result = subprocess.run(
        [
            sys.executable,
            "scripts/prepare_release_env.py",
            "--version",
            "2026.10.10-1",
            "--git-sha",
            "abcdef1234567890",
            "--built-at",
            "2026-10-10T01:30:00Z",
            "--application-image",
            _image("job-hub", DIGEST_A),
            "--browser-image",
            _image("job-hub-browser", DIGEST_B),
            "--browser-deps-image",
            _image("job-hub-browser-deps", DIGEST_C),
            "--headless-shell-image",
            _image("headless-shell", DIGEST_D),
            "--output",
            str(output),
        ],
        check=False,
        capture_output=True,
        text=True,
    )

    assert result.returncode == 0, result.stderr
    assert output.read_text(encoding="utf-8").startswith(
        "# Generated by scripts/prepare_release_env.py"
    )


def test_compose_overrides_development_release_values_from_release_manifest() -> None:
    compose = (Path(__file__).resolve().parent.parent / "docker-compose.yml").read_text(
        encoding="utf-8"
    )

    assert "x-release-environment: &release-environment" in compose
    assert compose.count("<<: *release-environment") == 2
    assert "APP_RELEASE_VERSION: ${APP_RELEASE_VERSION:-dev}" in compose


def test_production_compose_is_single_canonical_entrypoint() -> None:
    production = (Path(__file__).resolve().parent.parent / "deploy" / "compose.yaml")
    text = production.read_text(encoding="utf-8")
    assert "x-release-environment: &release-environment" in text
    assert "context: .." in text
    assert "../data:/app/data:ro" in text
    assert "overlay" not in text.lower()


def test_phase3_manifest_reads_only_immutable_release_identity(tmp_path) -> None:
    env = tmp_path / ".release.env"
    env.write_text(
        "APP_RELEASE_VERSION=phase3\n"
        "JOB_HUB_IMAGE=registry.example/job-hub@sha256:" + "a" * 64 + "\n"
        "SECRET_TOKEN=must-not-be-read\n",
        encoding="utf-8",
    )

    values = release_env_values(env)

    assert values["APP_RELEASE_VERSION"] == "phase3"
    assert "SECRET_TOKEN" not in values
    assert image_digest(values["JOB_HUB_IMAGE"]) == DIGEST_A
