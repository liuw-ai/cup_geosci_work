"""Generate a non-secret, immutable Docker Compose release manifest."""

from __future__ import annotations

import argparse
import re
import subprocess
from datetime import datetime, timezone
from pathlib import Path


_IMAGE_DIGEST_PATTERN = re.compile(r"^.+@(sha256:[0-9a-f]{64})$")
_GIT_SHA_PATTERN = re.compile(r"^[0-9a-f]{7,64}$")


def _digest(reference: str, label: str) -> str:
    match = _IMAGE_DIGEST_PATTERN.fullmatch(reference.strip())
    if match is None:
        raise ValueError(f"{label} must use an immutable @sha256:<64-hex> reference")
    return match.group(1)


def _default_git_sha() -> str:
    result = subprocess.run(
        ["git", "rev-parse", "HEAD"],
        check=True,
        capture_output=True,
        text=True,
    )
    return result.stdout.strip().lower()


def _utc_timestamp() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")


def render_manifest(
    *,
    version: str,
    git_sha: str,
    built_at: str,
    application_image: str,
    browser_image: str,
    browser_deps_image: str,
    headless_shell_image: str,
) -> str:
    normalized_version = version.strip()
    normalized_git_sha = git_sha.strip().lower()
    normalized_built_at = built_at.strip()
    if normalized_version in {"", "dev", "unknown"}:
        raise ValueError("version must be a non-development release identifier")
    if _GIT_SHA_PATTERN.fullmatch(normalized_git_sha) is None:
        raise ValueError("git_sha must be a Git commit SHA")
    try:
        parsed_built_at = datetime.fromisoformat(normalized_built_at.replace("Z", "+00:00"))
        if parsed_built_at.tzinfo is None:
            raise ValueError("timezone is required")
    except ValueError as error:
        raise ValueError("built_at must be an ISO-8601 timestamp with timezone") from error

    application_digest = _digest(application_image, "application_image")
    _digest(browser_image, "browser_image")
    _digest(browser_deps_image, "browser_deps_image")
    _digest(headless_shell_image, "headless_shell_image")
    return "\n".join(
        (
            "# Generated by scripts/prepare_release_env.py. It contains no secrets.",
            f"APP_RELEASE_VERSION={normalized_version}",
            f"APP_RELEASE_GIT_SHA={normalized_git_sha}",
            f"APP_RELEASE_IMAGE_SHA={application_digest}",
            f"APP_RELEASE_BUILT_AT={normalized_built_at}",
            f"JOB_HUB_IMAGE={application_image.strip()}",
            f"RUNTIME_IMAGE={application_image.strip()}",
            f"JOB_HUB_BROWSER_IMAGE={browser_image.strip()}",
            f"BROWSER_DEPS_IMAGE={browser_deps_image.strip()}",
            f"HEADLESS_SHELL_IMAGE={headless_shell_image.strip()}",
            "",
        )
    )


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Generate an immutable .release.env for Docker Compose."
    )
    parser.add_argument("--version", required=True)
    parser.add_argument("--application-image", required=True)
    parser.add_argument("--browser-image", required=True)
    parser.add_argument("--browser-deps-image", required=True)
    parser.add_argument("--headless-shell-image", required=True)
    parser.add_argument("--git-sha", default=None)
    parser.add_argument("--built-at", default=None)
    parser.add_argument("--output", type=Path, default=Path(".release.env"))
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    git_sha = args.git_sha or _default_git_sha()
    built_at = args.built_at or _utc_timestamp()
    try:
        rendered = render_manifest(
            version=args.version,
            git_sha=git_sha,
            built_at=built_at,
            application_image=args.application_image,
            browser_image=args.browser_image,
            browser_deps_image=args.browser_deps_image,
            headless_shell_image=args.headless_shell_image,
        )
    except ValueError as error:
        raise SystemExit(f"release manifest rejected: {error}") from error
    args.output.write_text(rendered, encoding="utf-8", newline="\n")
    print(f"Wrote immutable release manifest: {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
